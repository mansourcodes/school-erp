    /** Letters (without the vowel marks and Quranic signs) up to which a verse uses each text size. */
    protected const SIZES = ['lg' => 32, 'md' => 50];

    /** @return array{text: string, surah: string, ayah: string, size: string, number: string} */
    public static function random()
    {
        return Arr::random(self::all());
    }

    /** Every quote with its `size` (lg | md | sm) for the card's font step and its `number` as in the mushaf (١١٤). */
    public static function all()
    {
        return array_map(function ($quote) {
            return $quote + [
                'size' => self::size($quote['text']),
                'number' => strtr($quote['ayah'], ['0' => '٠', '1' => '١', '2' => '٢', '3' => '٣', '4' => '٤',
                    '5' => '٥', '6' => '٦', '7' => '٧', '8' => '٨', '9' => '٩', '-' => '–']),
            ];
        }, self::ALL);
    }

    public static function size($text)
    {
        // Harakat, superscript alef and the small Quranic marks add no width of their own.
        $letters = mb_strlen(preg_replace('/[\x{0610}-\x{061A}\x{064B}-\x{065F}\x{0670}\x{06D6}-\x{06ED}\s]/u', '', $text));

        foreach (self::SIZES as $size => $max) {
            if ($letters <= $max) {
                return $size;
            }
        }

        return 'sm';
    }
